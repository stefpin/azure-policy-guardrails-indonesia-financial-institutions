#!/usr/bin/env python3
"""Generate scripts/*.ps1 from the PowerShell code blocks of docs/runbook/*.md.

The runbook pages are the single source of truth. The scripts are a convenience copy,
meant to be run BLOCK BY BLOCK (not as one script).

    python tools/extract_scripts.py            write scripts/
    python tools/extract_scripts.py --check    fail if scripts/ is out of date
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs", "runbook")
OUT = os.path.join(ROOT, "scripts")

# (output file, title, source pages)
TARGETS = [
    ("10-part1-prepare-the-stage.ps1", "Part 1 - Prepare the stage", ["00-before-you-start.md", "01-prepare-the-stage.md"]),
    ("20-part2-chapter1-prevent.ps1", "Part 2 - Chapter 1: PREVENT", ["02-chapter-1-prevent.md"]),
    ("30-part3-chapter2-detect.ps1", "Part 3 - Chapter 2: DETECT", ["03-chapter-2-detect.md"]),
    ("40-part4-chapter3-remediate.ps1", "Part 4 - Chapter 3: REMEDIATE and PROVE", ["04-chapter-3-remediate-and-prove.md"]),
    ("50-part5-cleanup.ps1", "Part 5 - Wrap-up, reset and clean-up", ["05-wrap-up-and-clean-up.md"]),
]

HEADER = """<#
    {title}

    GENERATED from docs/runbook/{pages} by tools/extract_scripts.py.
    Do not edit this file: change the page and regenerate.

    HOW TO USE
      1. Edit $SUB and $OWNER in 00-variables.ps1, then dot-source the two shared files:
             . ./00-variables.ps1
             . ./01-helpers.ps1
      2. Run THIS file BLOCK BY BLOCK: select a block and press F8 (VS Code or the
         PowerShell ISE), or paste it into the terminal.

    DO NOT RUN IT AS ONE SCRIPT. Some commands are supposed to be REFUSED by Azure,
    some steps need you to wait for Azure Policy, and every step has a result you
    should read before you go on. The page explains each step.
#>
"""

SHARED_HEADER = """<#
    {title}

    GENERATED from docs/runbook/01-prepare-the-stage.md by tools/extract_scripts.py.
    Do not edit this file: change the page and regenerate.

    Dot-source it:   . ./{name}
#>
"""


def blocks_of(path):
    """Yield (h2, h3, code) for every top-level powershell fence of one page."""
    h2 = h3 = ""
    lines = io.open(path, encoding="utf-8").read().split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("## "):
            h2, h3 = ln[3:].strip(), ""
        elif ln.startswith("### "):
            h3 = ln[4:].strip()
        elif ln.rstrip() == "```powershell":
            j = i + 1
            body = []
            while j < len(lines) and lines[j].rstrip() != "```":
                body.append(lines[j])
                j += 1
            yield h2, h3, "\n".join(body)
            i = j
        i += 1


def render():
    files = {}
    shared = {"00-variables.ps1": None, "01-helpers.ps1": None}
    for out_name, title, pages in TARGETS:
        parts = []
        last = None
        for page in pages:
            for h2, h3, code in blocks_of(os.path.join(DOCS, page)):
                first = code.lstrip().split("\n", 1)[0]
                if first.startswith("# ---- Azure Policy guardrails demo variables"):
                    shared["00-variables.ps1"] = code
                    continue
                if first.startswith("function Show-Assignments"):
                    shared["01-helpers.ps1"] = code
                    continue
                key = (h2, h3)
                if key != last:
                    banner = "# " + "=" * 74 + "\n# " + (h2 or title)
                    if h3:
                        banner += "\n#   " + h3
                    banner += "\n# " + "=" * 74
                    parts.append(banner)
                    last = key
                parts.append(code.rstrip())
        pages_txt = ", ".join(pages)
        files[out_name] = HEADER.format(title=title, pages=pages_txt) + "\n" + "\n\n".join(parts) + "\n"
    for name, code in shared.items():
        if code is None:
            sys.exit("could not find the block for " + name)
        title = "Variables for the Azure Policy guardrails demo" if name.startswith("00") else "Helper commands for the Azure Policy guardrails demo"
        files[name] = SHARED_HEADER.format(title=title, name=name) + "\n" + code.rstrip() + "\n"
    return files


def main():
    files = render()
    check = "--check" in sys.argv
    bad = []
    os.makedirs(OUT, exist_ok=True)
    for name, text in sorted(files.items()):
        path = os.path.join(OUT, name)
        current = io.open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else None
        if current != text:
            bad.append(name)
            if not check:
                io.open(path, "w", encoding="utf-8", newline="\n").write(text)
    if check:
        if bad:
            print("scripts out of date: " + ", ".join(bad) + " - run: python tools/extract_scripts.py")
            return 1
        print("scripts are up to date (%d files)" % len(files))
        return 0
    print("wrote %d script(s); %d changed" % (len(files), len(bad)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
