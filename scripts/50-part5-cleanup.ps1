$enforcing = @(
  @('alz-pd-c1-lab',        $SCOPE_LAB),
  @('alz-pd-c3-lab',        $SCOPE_LAB),
  @('alz-pd-lab-nopeering', $SCOPE_LAB),
  @('alz-pd-rg-tags',       $SCOPE_SUB),
  @('alz-pd-rg-loc',        $SCOPE_SUB)
)
